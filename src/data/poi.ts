// coordinates. Hardcoded rather than pulled from a live POI API (none is
// configured), but every entry is an actual place, not fabricated data.
// Schools/Universities & Colleges/Hospitals/Clinics/Malls/Airports/Beaches/
// Golf/Parks sourced from a user-provided real POI dataset
// (dubai_places.csv, 1065 rows). A few of the CSV's raw categories are
// folded into the closest existing layer rather than getting their own
// toggle: Nursery/Kindergarten -> schools, Department Store/Shopping
// Centre -> malls, Heliport -> airports, Garden -> parks. College and
// University are distinct enough (a real, separate search consideration --
// e.g. rental demand near a university) to get their own "Universities &
// Colleges" layer; Clinic/Medical Centre likewise gets its own "Clinics"
// layer rather than being merged into Hospitals, since a walk-in clinic
// and a full hospital aren't the same thing to search for. Metro stations
// merge two datasets: dubai_all_metro_lines.csv (operational Red/Green
// lines) and dubai_blue_gold_metro_locations.csv (planned/under-construction
// Blue/Gold lines, approximate coordinates). Each point carries its own
// color by line (Red/Green/Blue/Gold) instead of one flat color for all
// metro pins. Real interchange stations shared by two lines (Centrepoint,
// Union, BurJuman, Business Bay, Jumeirah Golf Estates, Al Gubaiba, Creek)
// are merged into a single pin listing both lines. Blue/Gold stations that
// aren't built yet keep their planning status in the label for honesty.

